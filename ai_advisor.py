def _extract_tomorrow_forecast_row(forecast: dict) -> dict | None:
    """Pulls out tomorrow's (index 1) values from a data_feeds.fetch_*_
    forecast()-shaped dict. Returns None if there's no tomorrow row at all
    (never fabricates a forecast that wasn't actually returned)."""
    dates = forecast.get("dates") or []
    if len(dates) < 2:
        return None
    row = {"date": dates[1]}
    for key, values in forecast.items():
        if key in ("dates", "source") or not isinstance(values, list):
            continue
        if len(values) > 1:
            row[key] = values[1]
    return row


def generate_tomorrow_preshift_briefing(
    site_name: str,
    module: str,
    forecast: dict,
    api_key: str | None,
    lang: str = "fr",
) -> dict:
    """
    J+1 shift-planning layer: ingests tomorrow's forecast row (from a
    data_feeds.fetch_solar_forecast()/fetch_offshore_forecast()-shaped
    dict) and produces "Tomorrow's Crew Pre-Briefing Note" - actionable
    guidance for the scheduler on specific work-window adjustments (e.g.
    suspending morning crane lifts ahead of an expected wind spike, or
    moving heavy-exertion tasks to a cooler window ahead of an expected
    heat spike), read the evening before rather than reacted to the next
    morning.

    Falls back to a templated note (raw tomorrow's forecast values, no
    AI-generated tactical advice) if no API key is supplied, the call
    fails, or fewer than 2 days of forecast data are available - never
    fabricates a forecast value that wasn't actually returned by
    data_feeds.py.

    Returns {"note": str, "source": "ai" | "template" | "insufficient_data",
    "tomorrow_date": str | None, "error_kind": str | None}.
    """
    tomorrow = _extract_tomorrow_forecast_row(forecast)
    if tomorrow is None:
        return {
            "note": _INSUFFICIENT_FORECAST_NOTE.get(lang, _INSUFFICIENT_FORECAST_NOTE["fr"]),
            "source": "insufficient_data", "tomorrow_date": None, "error_kind": None,
        }

    summary_parts = [f"{_FORECAST_FIELD_LABELS.get(k, k)}: {v}" for k, v in tomorrow.items() if k != "date"]
    summary_text = "; ".join(summary_parts) or "no forecast fields available"

    if not api_key:
        return {
            "note": _NO_KEY_FORECAST_TEMPLATE.get(lang, _NO_KEY_FORECAST_TEMPLATE["fr"]).format(
                date=tomorrow["date"], summary=summary_text
            ),
            "source": "template", "tomorrow_date": tomorrow["date"], "error_kind": None,
        }

    lang_instruction = _language_instruction(lang)
    prompt = (
        "You are an HSE scheduling assistant. Given tomorrow's forecast for a "
        "construction site, write a short 'Tomorrow's Crew Pre-Briefing Note' "
        "(under 150 words) for the scheduler to read tonight, BEFORE tomorrow's "
        "shift is planned. Recommend SPECIFIC work-window adjustments if the "
        "forecast warrants them (e.g. 'suspend morning crane lifts before 10:00, "
        "expected wind spike', 'move heavy-exertion tasks to before 11:00 ahead "
        "of forecast peak heat'). If tomorrow's forecast is unremarkable for this "
        "module, say so briefly rather than inventing a concern. Do not invent "
        "a name for anyone.\n\n"
        f"{lang_instruction}\n\n"
        f"SITE: {site_name}\nMODULE: {module}\n"
        f"TOMORROW'S DATE: {tomorrow['date']}\nTOMORROW'S FORECAST: {summary_text}"
    )

    try:
        resp = requests.post(
            ANTHROPIC_URL,
            headers={
                "x-api-key": api_key,
                "anthropic-version": "2023-06-01",
                "content-type": "application/json",
            },
            json={"model": MODEL, "max_tokens": 400, "messages": [{"role": "user", "content": prompt}]},
            timeout=20,
        )
        resp.raise_for_status()
        data = resp.json()
        parts = [b["text"] for b in data.get("content", []) if b.get("type") == "text"]
        note = "\n".join(parts).strip()
        if not note:
            raise ValueError("empty response")
        return {"note": note, "source": "ai", "tomorrow_date": tomorrow["date"], "error_kind": None}
    except Exception as exc:  # noqa: BLE001
        return {
            "note": _NO_KEY_FORECAST_TEMPLATE.get(lang, _NO_KEY_FORECAST_TEMPLATE["fr"]).format(
                date=tomorrow["date"], summary=summary_text
            ),
            "source": "template", "tomorrow_date": tomorrow["date"], "error_kind": classify_api_error(exc),
        }
