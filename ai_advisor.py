def _worker_strain_instruction(worker_strain_summary: list[dict] | None) -> str:
    """Builds the 'cross-reference live biometric strain' instruction block.
    worker_strain_summary is a list of risk_engine.calculate_physiological_
    strain() result dicts (or an equivalent minimal shape with at least
    'status'/'pct_hr_max') for whichever anonymized workers currently have
    a reading. None/empty means no wearable data is active for this
    assessment - the model is told that explicitly rather than left to
    guess, so it never fabricates a biometric reading that wasn't supplied."""
    if not worker_strain_summary:
        return (
            "No live worker biometric/wearable data is available for this assessment - "
            "base the action plan on environmental readings only."
        )
    critical = [w for w in worker_strain_summary if w.get("status") == "CRITICAL"]
    warning = [w for w in worker_strain_summary if w.get("status") == "WARNING"]
    lines = [
        f"- {w.get('worker_id', 'Worker')}: {w.get('status')} ({w.get('pct_hr_max', '?')}% max HR, "
        f"est. core temp {w.get('estimated_core_temp_c', '?')}C)"
        for w in worker_strain_summary
    ]
    priority_note = (
        "AT LEAST ONE WORKER IS AT CRITICAL PHYSIOLOGICAL STRAIN RIGHT NOW. "
        "Prioritize an immediate human-strain response (stop work / rotate / cool down "
        "that individual) as the single most urgent action, ranked ABOVE any raw "
        "environmental WBGT/Humidex-only recommendation - real-time cardiac load takes "
        "precedence over a meteorological threshold that hasn't yet been crossed."
        if critical else
        "One or more workers are at WARNING-level physiological strain. Reference this "
        "directly alongside the environmental reading and recommend closer monitoring or "
        "an earlier rotation than the environmental threshold alone would suggest."
        if warning else
        "All monitored workers are currently within SAFE physiological strain - you may "
        "still mention this briefly as reassuring context."
    )
    return (
        "LIVE WORKER BIOMETRIC / WEARABLE DATA (anonymized profile markers only):\n"
        + "\n".join(lines) + f"\n\n{priority_note}"
    )


def _build_narrative_request(
    result: dict,
    controls: list,
    lang: str,
    enable_web_search: bool = False,
    worker_strain_summary: list[dict] | None = None,
) -> tuple[str, dict]:
    """Builds the exact prompt string and any extra request_body fields
    (currently just 'tools' when enable_web_search=True) shared by every
    narrative-generating entry point (the original synchronous call, the
    cached wrapper, the streaming generator, and the background async
    job) - extracted so all four stay byte-for-byte consistent instead of
    four copies of the same prompt logic drifting apart over time.
    Returns (prompt, extra_request_fields)."""
    language_instruction = _language_instruction(lang)

    references = get_references(result.get("module", ""))
    references_text = "\n".join(
        f"- {ref['region']} / {ref['body']}: {ref['doc']}" + (f" ({ref['url']})" if ref.get("url") else "")
        for ref in references
    ) or "- No pre-verified references available for this module."

    jurisdiction_label = result.get("regulatory_profile_label", "")
    jurisdiction_instruction = (
        f"This assessment was evaluated under the following ACTIVE regulatory "
        f"jurisdiction: {jurisdiction_label}. When a recommendation or "
        "stop-work condition stems from a jurisdiction-specific rule (e.g. a "
        "mandatory thermal/heat rotation, a statutory midday outdoor-work "
        "ban, a Humidex or Wind Chill threshold, a UV/sun-protection "
        "trigger, or an isolated/remote-worker communication requirement), "
        "name the specific regulatory body by its real name (for example: "
        "'According to CNESST guidelines, a mandatory thermal rotation is "
        "required...', 'Per HSE COSHH exposure limits...', 'Under Safe Work "
        "Australia's model WHS Regulations...'). Only name a body/framework "
        "that appears here or in the verified reference list below - never "
        "invent one."
        if jurisdiction_label else
        "No active regulatory jurisdiction label was supplied with this "
        "assessment - do not name a specific regulatory body; refer to "
        "applicable local and international HSE standards generally."
    )

    search_instruction = (
        "You have a web_search tool available. You may use it (a few searches "
        "at most) to check for current, jurisdiction-specific guidance or "
        "recent amendments relevant to this assessment. If you use it, cite "
        "the specific source name and URL you found - never state a figure, "
        "clause, or threshold from a search result without naming where it "
        "came from."
        if enable_web_search else
        "Do not search the web. Base your citations only on the verified "
        "reference list supplied below."
    )

    worker_strain_instruction = _worker_strain_instruction(worker_strain_summary)

    prompt = (
        "You are an HSE risk communication assistant grounded in an authentic "
        "safety-culture philosophy: compliance is the OUTPUT of a genuine "
        "safety culture, not administrative theater, and the real test of "
        "that culture is whether leadership chooses to control the risk or "
        "cut the cost when the two are in tension.\n\n"
        "Given this structured construction risk assessment output "
        "(JSON-like), write a concise operational briefing for an HSE "
        "manager: risk level, primary hazard, the single most urgent "
        "action, and a stop-work condition if applicable. Be direct, "
        "professional, no fluff.\n\n"
        "CITATION RULES (do not violate these):\n"
        "- Only cite the standards bodies/documents listed below, or ones "
        "you find via live web search and can name with a real URL.\n"
        "- NEVER invent a named methodology, 'principles', framework, or "
        "clause/section number that you are not certain is real. If unsure, "
        "name the standards body generally (e.g. 'consult applicable OSHA "
        "guidance') rather than inventing a specific citation.\n"
        f"- {search_instruction}\n\n"
        f"VERIFIED REFERENCES FOR THIS MODULE:\n{references_text}\n\n"
        f"ACTIVE JURISDICTION:\n{jurisdiction_instruction}\n\n"
        f"{worker_strain_instruction}\n\n"
        f"{language_instruction}\n\n"
        f"DATA: {result}\n\nRECOMMENDED CONTROLS: {controls}"
    )

    extra: dict = {}
    if enable_web_search:
        extra["tools"] = [{"type": "web_search_20250305", "name": "web_search", "max_uses": WEB_SEARCH_MAX_USES}]
