def _fallback_narrative(result: dict, controls: list, lang: str = "fr") -> str:
    """
    Offline/no-key fallback narrative, localized for all 14 supported UI
    languages; the underlying risk_band/primary_hazard/controls values
    themselves stay in English (they're the transparent engine's raw
    vocabulary). Unknown language codes fall back to French, matching this
    app's existing default-language convention.

    For elevated risk bands, appends a short line reflecting the safety
    culture principle above: this is the moment where leadership either
    controls the risk or cuts the cost, and that choice - not the paperwork -
    is what the AI briefing is here to surface.

    The regulatory basis line now leads with the ACTIVE jurisdiction (e.g.
    "Canada (OHS / CNESST)") when the result carries one, before the
    module's general citation list - so even the offline, no-API-key
    narrative names the specific active jurisdiction, not just a generic
    module reference list.
    """
    band = result.get("risk_band", "Unknown")
    hazard = result.get("primary_hazard", "")
    default_control = _FALLBACK_NARRATIVE_DEFAULT_CONTROL.get(
        lang, _FALLBACK_NARRATIVE_DEFAULT_CONTROL["fr"]
    )
    top_control = controls[0] if controls else default_control

    elevated = str(band).upper() in ("HIGH", "EXTREME", "CRITICAL", "EXTREME (DANGER)")

    regulatory_basis = _regulatory_basis(result)

    template = _FALLBACK_NARRATIVE_MAIN.get(lang, _FALLBACK_NARRATIVE_MAIN["fr"])
    text = template.format(
        band=band, hazard=hazard, top_control=top_control, regulatory_basis=regulatory_basis
    )
    if elevated:
        text += _FALLBACK_NARRATIVE_ELEVATED_SUFFIX.get(lang, _FALLBACK_NARRATIVE_ELEVATED_SUFFIX["fr"])
    return text


def _regulatory_basis(result: dict) -> str:
    """Return named frameworks relevant to the assessed environment. Leads
    with the ACTIVE jurisdiction's own label (result['regulatory_profile_label'],
    e.g. 'Canada (OHS / CNESST)') when present, so requirement #3 (name the
    specific active jurisdiction, e.g. 'According to CNESST guidelines...')
    is honored even in the offline no-API-key narrative - then appends the
    module's general citation bodies from the single verified citation list
    in regulatory_references.py (never a separate hardcoded list), so this
    stays consistent with the full Regulatory References section and never
    names an unverified framework."""
    jurisdiction_label = result.get("regulatory_profile_label")

    refs = get_references(result.get("module", ""))
    bodies = []
    for ref in refs:
        if ref["body"] not in bodies:
            bodies.append(ref["body"])

    if jurisdiction_label:
        rest = "; ".join(b for b in bodies if b not in jurisdiction_label)
        return f"{jurisdiction_label}" + (f"; {rest}" if rest else "")
    return "; ".join(bodies) if bodies else "consult applicable local and international HSE standards"


# ---------------------------------------------------------------------------
# Module 5b: Offline-first fault tolerance - shared error classification
# ---------------------------------------------------------------------------
# generate_narrative() above already never lets an API failure break the
# app (it always falls back to _fallback_narrative()). This helper adds the
# one thing that was still generic ("[AI narrative unavailable: <exception>]"):
# telling the caller (app.py's toast) *what kind* of failure this was, so a
# site foreman on a spotty cellular connection sees "poor network coverage"
# rather than a raw Python exception string.
def classify_api_error(exc: Exception) -> str:
    """Returns one of 'network', 'timeout', 'auth', 'rate_limit', 'other' -
    used by app.py to pick the right offline-mode toast message."""
    text = str(exc).lower()
    if isinstance(exc, requests.exceptions.Timeout) or "timeout" in text:
        return "timeout"
    if isinstance(exc, (requests.exceptions.ConnectionError, requests.exceptions.SSLError)):
        return "network"
    if "401" in text or "invalid x-api-key" in text or "authentication" in text:
        return "auth"
    if "429" in text or "rate limit" in text:
        return "rate_limit"
    return "other"


