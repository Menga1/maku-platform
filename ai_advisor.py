def generate_narrative(
    result: dict,
    controls: list,
    api_key: str,
    lang: str = "fr",
    enable_web_search: bool = False,
    worker_strain_summary: list[dict] | None = None,
) -> str:
    """
    Calls the Anthropic API to turn the structured risk_engine output into a
    short HSE-manager-facing narrative. Falls back gracefully if no key is
    provided or the call fails - the app must never depend on this to function.

    lang: UI language code ("fr" default, or "en"). Per project guidelines the
    app defaults to French, so the AI briefing is requested in French unless
    the user has switched to English. The underlying data/controls stay in
    English (they come straight from the transparent risk_engine/ai_advisor
    logic) - only the generated narrative text is localized.

    enable_web_search: opt-in only (costs extra API usage/latency). When True
    and an api_key is supplied, enables Claude's built-in web_search tool so
    the model can look up current, jurisdiction-specific guidance live and
    cite real URLs, on top of (never instead of) the verified reference list
    below. This reuses the same Anthropic API key already required for the
    narrative - no separate search API key needed.

    worker_strain_summary: optional list of risk_engine.
    calculate_physiological_strain() results for currently-monitored
    anonymized workers - when supplied, the model is instructed to
    cross-reference real-time cardiac load against the environmental
    WBGT/Humidex reading and prioritize a CRITICAL/WARNING biometric
    signal over a raw meteorological threshold. None (the default) keeps
    every pre-existing call site's behavior byte-for-byte unchanged.

    Grounding note: the prompt supplies the model with the EXACT verified
    regulatory references for this module (from regulatory_references.py)
    and explicitly forbids inventing named methodologies, "principles",
    clause numbers, or frameworks beyond what's supplied or found via live
    search. An earlier version of this prompt instructed the model to
    invoke "Roger Bauer's... risk-analysis principles" as if it were an
    established methodology - that was a fabrication risk (same category of
    problem regulatory_references.py exists to prevent) and has been
    removed entirely.
    """
    if not api_key:
        return _fallback_narrative(result, controls, lang)
    try:
        return _request_narrative_text(result, controls, api_key, lang, enable_web_search, worker_strain_summary)
    except NarrativeUnavailable as exc:
        return _fallback_narrative(result, controls, lang) + "\n\n" + ai_unavailable_note(lang, exc.kind)


def _request_narrative_text(
    result: dict,
    controls: list,
    api_key: str,
    lang: str,
    enable_web_search: bool,
    worker_strain_summary: list[dict] | None,
) -> str:
    """One live Anthropic call. Returns model text, or RAISES
    NarrativeUnavailable - it never returns a fallback/error string, which
    is what makes it safe to wrap in st.cache_data."""
    prompt, extra = _build_narrative_request(result, controls, lang, enable_web_search, worker_strain_summary)
    request_body = {
        "model": MODEL,
        "max_tokens": 700,
        "messages": [{"role": "user", "content": prompt}],
        **extra,
    }
    try:
        resp = requests.post(
            ANTHROPIC_URL,
            headers={
                "x-api-key": api_key,
                "anthropic-version": "2023-06-01",
                "content-type": "application/json",
            },
            json=request_body,
            timeout=40 if enable_web_search else 20,
        )
        resp.raise_for_status()
        data = resp.json()
    except Exception as exc:  # noqa: BLE001
        kind = classify_api_error(exc)
        logger.warning("Anthropic narrative request failed (%s): %s", kind, exc)
        raise NarrativeUnavailable(kind) from exc
    text_parts = [b["text"] for b in data.get("content", []) if b.get("type") == "text"]
    text = "\n".join(text_parts).strip()
    if not text:
        logger.warning("Anthropic narrative request returned no text")
        raise NarrativeUnavailable("empty_response")
    return text


@st.cache_data(ttl=NARRATIVE_CACHE_TTL_SECONDS, show_spinner=False, max_entries=500)
def _narrative_success_cached(
    result: dict,
    controls: list,
    key_fingerprint: str,
    lang: str,
    enable_web_search: bool,
    worker_strain_summary: list[dict] | None,
    _api_key: str,
) -> str:
    """Caches SUCCESSFUL model output only (see _request_narrative_text).
    key_fingerprint is part of the cache key; the raw key (_api_key) is not."""
    return _request_narrative_text(result, controls, _api_key, lang, enable_web_search, worker_strain_summary)


def generate_narrative_cached(
    result: dict,
    controls: list,
    _api_key: str | None,
    lang: str = "fr",
    enable_web_search: bool = False,
    worker_strain_summary: list[dict] | None = None,
) -> str:
    """
    Same contract as generate_narrative() (always returns a string, never
    raises), with a 30-minute cache of successful responses per
    (inputs, API-key fingerprint). A 429/timeout/network failure is never
    cached: the next request retries the API instead of replaying an error
    to every user for half an hour.
    """
    if not _api_key:
        return _fallback_narrative(result, controls, lang)
    try:
        return _narrative_success_cached(
            result, controls, api_key_fingerprint(_api_key), lang, enable_web_search,
            worker_strain_summary, _api_key,
        )
    except NarrativeUnavailable as exc:
        return _fallback_narrative(result, controls, lang) + "\n\n" + ai_unavailable_note(lang, exc.kind)


# ---------------------------------------------------------------------------
# Token streaming (renders word-by-word instead of freezing the interface)
# ---------------------------------------------------------------------------
# Uses the `anthropic` SDK's synchronous streaming client - a plain
# generator, meant to be handed directly to Streamlit's own st.write_stream()
# in app.py, which iterates it and updates the display incrementally as
# each chunk arrives, then returns the fully concatenated text. This is
# the real stream=True request/response path (Server-Sent Events under
# the hood), not a fake client-side typewriter effect over an already-
# complete string.

def generate_narrative_stream_chunks(
    result: dict,
    controls: list,
    api_key: str,
    lang: str = "fr",
    enable_web_search: bool = False,
    worker_strain_summary: list[dict] | None = None,
):
    """
    Generator yielding narrative text chunks as they stream in from the
    Anthropic API (stream=True). Intended usage in app.py:
        narrative = st.write_stream(generate_narrative_stream_chunks(...))
    which renders each chunk live and returns the joined final string.

    Falls back to yielding the complete offline/fallback narrative as a
    single chunk (st.write_stream handles a single-item generator fine)
    when no api_key is supplied or the `anthropic` SDK isn't installed -
    streaming is a progressive rendering enhancement, never a hard
    requirement for the narrative to appear at all.

    Deliberately NOT cached (see generate_narrative_cached's docstring) -
    every call here is a fresh, live API request, because the whole point
    of showing a stream is that the user is watching it happen right now.
    """
    if not api_key or not ANTHROPIC_SDK_AVAILABLE:
        yield generate_narrative(result, controls, api_key, lang, enable_web_search, worker_strain_summary)
        return

    prompt, extra = _build_narrative_request(result, controls, lang, enable_web_search, worker_strain_summary)
    try:
        client = Anthropic(api_key=api_key)
        kwargs = dict(model=MODEL, max_tokens=700, messages=[{"role": "user", "content": prompt}], **extra)
        got_any_text = False
        with client.messages.stream(**kwargs) as stream:
            for text in stream.text_stream:
                got_any_text = True
                yield text
        if not got_any_text:
            yield _fallback_narrative(result, controls, lang)
    except Exception as e:  # noqa: BLE001 - never let a streaming failure blank the page
        kind = classify_api_error(e)
        logger.warning("Anthropic streaming request failed (%s): %s", kind, e)
        yield "\n\n" + _fallback_narrative(result, controls, lang) + "\n\n" + ai_unavailable_note(lang, kind)


# ---------------------------------------------------------------------------
# Background async generation (AsyncAnthropic on a worker thread), so the
# rest of the page - including analytics.py's charts, already rendered
# earlier in the same script run - stays interactive while the narrative
# generates.
# ---------------------------------------------------------------------------
# HONEST DESIGN NOTE: Streamlit's script execution model reruns the whole
# script top-to-bottom per interaction and is single-threaded within that
# run - a plain synchronous (or even a bare `await`ed async) API call still
# blocks that entire run until it returns, identical to the old
# requests.post() behavior. A background Python thread is what actually
# makes the rest of the page interactive during generation: the button
# handler starts the thread and returns immediately, and a
# st.fragment(run_every=...) poller (see app.py) reruns ONLY itself on a
# timer to display newly-arrived tokens, never forcing the whole page (and
# its already-rendered analytics charts) to rerun. AsyncAnthropic is the
# client actually used to talk to the API inside that thread, per the
# request - the thread is what delivers the non-blocking UX, AsyncAnthropic
# is what performs the (concurrency-friendly) call within it.

class NarrativeStreamJob:
    """Thread-safe handle for one background streaming narrative job.
    The worker thread (see _run_stream_worker) only ever writes to
    `_queue`/`done`/`error`/`full_text`; app.py's st.fragment poller
    (running on Streamlit's main thread) only ever reads them via
    pull_available_tokens()."""

    def __init__(self) -> None:
        self._queue: "queue.Queue[str]" = queue.Queue()
        self.done = False
        # A failure KIND ('rate_limit', 'timeout', ...) - never raw exception
        # text, so nothing technical can leak into the UI from here.
        self.error: str | None = None
        self.full_text = ""

    def pull_available_tokens(self) -> list[str]:
        """Drains whatever chunks have arrived since the last poll -
        non-blocking, safe to call every fragment tick even if nothing
        new has arrived yet."""
        chunks = []
        while True:
            try:
                chunks.append(self._queue.get_nowait())
            except queue.Empty:
                break
        return chunks


def _run_stream_worker(job: NarrativeStreamJob, prompt: str, extra: dict, api_key: str) -> None:
    """Runs on a background thread - never on Streamlit's main script-run
    thread. Drives AsyncAnthropic via asyncio.run() inside this dedicated
    thread (each thread gets its own event loop this way, which is the
    supported pattern for running asyncio code outside a thread that
    already has a running loop, like Streamlit's main thread might)."""
    async def _consume() -> None:
        client = AsyncAnthropic(api_key=api_key)
        try:
            kwargs = dict(model=MODEL, max_tokens=700, messages=[{"role": "user", "content": prompt}], **extra)
            async with client.messages.stream(**kwargs) as stream:
                async for text in stream.text_stream:
                    job._queue.put(text)
                    job.full_text += text
        finally:
            await client.close()

    try:
        asyncio.run(_consume())
    except Exception as e:  # noqa: BLE001 - surfaced to the poller, never crashes the thread silently
        job.error = classify_api_error(e)
        logger.warning("Background narrative job failed (%s): %s", job.error, e)
    finally:
        job.done = True
        _AI_JOB_SLOTS.release()


def start_narrative_background_job(
    result: dict,
    controls: list,
    api_key: str,
    lang: str = "fr",
    enable_web_search: bool = False,
    worker_strain_summary: list[dict] | None = None,
) -> "NarrativeStreamJob | None":
    """
    Kicks off streaming narrative generation on a background thread and
    returns immediately with a job handle for app.py to poll from a
    st.fragment(run_every=...). Returns None (caller should fall back to
    generate_narrative_cached()/generate_narrative_stream_chunks()) when
    no api_key is supplied or the `anthropic` SDK isn't installed -
    background generation is a progressive-enhancement layer, never a
    hard requirement, matching this module's offline-first guarantee.
    """
    if not api_key or not ANTHROPIC_SDK_AVAILABLE:
        return None
    # Concurrency cap: when every slot is busy, return None so the caller
    # uses the synchronous cached path instead of piling up threads.
    if not _AI_JOB_SLOTS.acquire(blocking=False):
        logger.info("AI background job cap (%s) reached - using synchronous path", _AI_MAX_CONCURRENT_JOBS)
        return None
    try:
        prompt, extra = _build_narrative_request(result, controls, lang, enable_web_search, worker_strain_summary)
        job = NarrativeStreamJob()
        thread = threading.Thread(target=_run_stream_worker, args=(job, prompt, extra, api_key), daemon=True)
        thread.start()
    except Exception:  # noqa: BLE001 - never leak a slot if the thread could not start
        _AI_JOB_SLOTS.release()
        raise
    return job


