# Module 4 (part 2): Predictive forecasting layer
# ---------------------------------------------------------------------------
# Mathematical Isolation rule still applies: this NEVER computes a new risk
# number. It runs the SAME risk_engine function the module already uses,
# once per forecast point, and looks at the sequence of already-trusted
# risk_band values it returns. The only new "logic" here is "does the band
# get worse later", which is orchestration, not a risk formula.

_SEVERITY_ORDER = ["LOW", "MODERATE", "HIGH", "CRITICAL",
                   "Low", "Moderate", "High", "Extreme"]  # covers both naming conventions used across modules


def _severity_rank(band: str) -> int:
    try:
        return _SEVERITY_ORDER.index(band)
    except ValueError:
        return -1  # unknown label - treated as "can't compare", never as "safe"


def predict_forecast_breach(risk_fn, current_kwargs: dict, forecast_points: list[dict]) -> dict:
    """
    Runs risk_fn(**current_kwargs) plus risk_fn(**point) for every point in
    forecast_points (each point is a kwargs dict matching risk_fn's
    signature, plus an optional "label" key like "14:00" or "in 4h" used
    only for display - it's popped before the call). Flags the first
    forecast point where risk crosses into a worse band than the current
    reading, or into a safety-override state, whichever comes first.

    Works across every module's risk function unchanged, since it only
    reads the standard risk_band/safety_override fields every
    calculate_*_kinetic_risk() function already returns.

    Returns:
        {
          "currently_critical": bool,
          "will_breach": bool,
          "breach_label": str | None,
          "breach_band": str | None,
          "current_band": str,
        }
    """
    current_result = risk_fn(**current_kwargs)
    current_band = current_result.get("risk_band", "Unknown")
    current_rank = _severity_rank(current_band)
    currently_critical = bool(current_result.get("safety_override"))

    if currently_critical:
        return {
            "currently_critical": True, "will_breach": False,
            "breach_label": None, "breach_band": current_band, "current_band": current_band,
        }

    for point in forecast_points:
        point = dict(point)
        label = point.pop("label", None)
        forecast_result = risk_fn(**point)
        forecast_band = forecast_result.get("risk_band", "Unknown")
        forecast_rank = _severity_rank(forecast_band)
        if forecast_result.get("safety_override") or (forecast_rank > current_rank >= 0):
            return {
                "currently_critical": False, "will_breach": True,
                "breach_label": label, "breach_band": forecast_band, "current_band": current_band,
            }

    return {
        "currently_critical": False, "will_breach": False,
        "breach_label": None, "breach_band": None, "current_band": current_band,
    }


