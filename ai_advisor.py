def translate_narrative(text: str, target_lang: str, api_key: str | None,
                         dialect: str = "msa") -> dict:
    """
    Translates an already-generated AI briefing into another language on
    demand - e.g. an HSE manager reads the French briefing, then translates
    it to Arabic (optionally in Gulf or Egyptian dialect) to read aloud to
    the crew, without re-running the whole risk assessment.

    HONEST LIMITATION: this is a live-API-only feature. There is no
    reliable, production-safe offline translation path bundled with this
    app (a real offline MT model is far too heavy for this deployment, and
    unofficial free-translate APIs are not something a safety tool should
    depend on silently). If no key is supplied or the call fails, this
    returns the ORIGINAL text unchanged with an explicit note - it never
    fabricates a translation or silently returns text in the wrong
    language, since that would be actively dangerous for a safety briefing.

    Returns {"text": str, "translated": bool, "error_kind": str | None}.
    """
    if target_lang not in _TRANSLATE_TARGET_NAMES:
        return {"text": text, "translated": False, "error_kind": "unsupported_language"}

    if not api_key:
        return {"text": text, "translated": False, "error_kind": "no_api_key"}

    target_name = _TRANSLATE_TARGET_NAMES[target_lang]
    dialect_note = ""
    if target_lang == "ar":
        dialect_note = "\n\n" + ARABIC_DIALECT_INSTRUCTIONS.get(dialect, ARABIC_DIALECT_INSTRUCTIONS["msa"])

    prompt = (
        f"Translate the following HSE safety briefing into {target_name}. "
        "Preserve all numbers, units, and technical acronyms (WBGT, ACGIH, OEL, "
        "PM2.5, kW, cal/cm2, dBA, etc.) exactly as given - do not convert units. "
        "Output ONLY the translation, no preamble, no explanation."
        f"{dialect_note}\n\n"
        f"TEXT TO TRANSLATE:\n{text}"
    )

    try:
        resp = requests.post(
            ANTHROPIC_URL,
            headers={
                "x-api-key": api_key,
                "anthropic-version": "2023-06-01",
                "content-type": "application/json",
            },
            json={"model": MODEL, "max_tokens": 700, "messages": [{"role": "user", "content": prompt}]},
            timeout=20,
        )
        resp.raise_for_status()
        data = resp.json()
        parts = [b["text"] for b in data.get("content", []) if b.get("type") == "text"]
        translated = "\n".join(parts).strip()
        if not translated:
            return {"text": text, "translated": False, "error_kind": "empty_response"}
        return {"text": translated, "translated": True, "error_kind": None}
    except Exception as exc:  # noqa: BLE001
        return {"text": text, "translated": False, "error_kind": classify_api_error(exc)}


