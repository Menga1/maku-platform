def _resolve_ai_config() -> dict:
    """
    CONFIGURATION EXTERNALIZATION (Phase 2.2): the model identifier, API
    base URL, and web-search max_uses parameter used to be plain hardcoded
    module constants. They are now resolved from configuration external to
    this source file - same secrets-then-env-then-default resolution order
    auth.py already uses for credentials (see that module's docstring) -
    so an operator can point this app at a new model string, a different
    API endpoint (e.g. an enterprise API gateway in front of Anthropic's
    API), or a different web-search budget without editing source code and
    redeploying.

    Resolution order per value:
      1. st.secrets["ai"]["model"] / ["api_base_url"] / ["web_search_max_uses"]
         / ["api_key"] - see .streamlit/secrets.toml.example for the exact
         TOML shape.
      2. MAKU_AI_MODEL / MAKU_AI_API_BASE_URL / MAKU_AI_WEB_SEARCH_MAX_USES
         / MAKU_AI_API_KEY environment variables.
      3. The hardcoded defaults below, which match this file's original
         values exactly - an unconfigured deployment behaves identically to
         before this refactor. This is purely additive externalization, not
         a behavior change. api_key has no default - None means "no
         server-side key configured", which is a valid, supported state
         (see get_configured_ai_api_key()'s docstring).

    Every lookup is individually wrapped in try/except so a missing
    secrets.toml, a missing [ai] table, or a malformed value can never
    raise - it just falls through to the next source, exactly like
    auth._configured_users() does for credentials.

    P0 "AUTHENTICATION & CRYPTOGRAPHIC HARDENING" - CONFIG EXTERNALIZATION:
    api_key resolution is what lets app.py's sidebar stop requiring every
    individual operator to paste in their own personal Anthropic API key
    (a "local user API key constraint") - once a server-side key is
    configured here, the whole deployment shares one centrally-managed,
    st.secrets-held credential instead. See
    get_configured_ai_api_key()/render_ai_layer_sidebar-equivalent in
    app.py's _render_ai_layer_sidebar().
    """
    try:
        model = str(st.secrets["ai"]["model"]).strip() or None
    except Exception:  # noqa: BLE001 - no secrets.toml / no [ai] table / no "model" key
        model = None
    try:
        api_base_url = str(st.secrets["ai"]["api_base_url"]).strip() or None
    except Exception:  # noqa: BLE001
        api_base_url = None
    try:
        web_search_max_uses = int(st.secrets["ai"]["web_search_max_uses"])
    except Exception:  # noqa: BLE001
        web_search_max_uses = None
    try:
        api_key = str(st.secrets["ai"]["api_key"]).strip() or None
    except Exception:  # noqa: BLE001
        api_key = None

    model = model or os.environ.get("MAKU_AI_MODEL", "").strip() or "claude-sonnet-4-5"
    api_base_url = (
        api_base_url
        or os.environ.get("MAKU_AI_API_BASE_URL", "").strip()
        or "https://api.anthropic.com/v1/messages"
    )
    if web_search_max_uses is None:
        env_max_uses = os.environ.get("MAKU_AI_WEB_SEARCH_MAX_USES", "").strip()
        web_search_max_uses = int(env_max_uses) if env_max_uses.isdigit() else 3
    api_key = api_key or os.environ.get("MAKU_AI_API_KEY", "").strip() or None

    return {"model": model, "api_base_url": api_base_url, "web_search_max_uses": web_search_max_uses,
            "api_key": api_key}


