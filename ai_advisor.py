# Languages whose native script is not Latin - technical acronyms and units
# (WBGT, ACGIH, OEL, PM2.5, kW, cal/cm2, dBA...) are kept in Latin script for
# these, matching standard practice in each language's own technical and
# engineering documentation - the app already did this for Arabic and
# Spanish; this generalizes the same rule to every non-Latin-script language.
NON_LATIN_SCRIPT_LANGS = {"ar", "zh", "ja", "hi", "ur"}


def _language_instruction(lang: str) -> str:
    """Builds the 'write your response in <language>' instruction sent to
    the Anthropic API for generate_narrative()/generate_daily_briefing().
    Unknown language codes fall back to French, matching this app's
    existing default-language convention."""
    name = LANGUAGE_DISPLAY_NAMES.get(lang, "French")
    instruction = f"Write your response in {name}."
    if lang in NON_LATIN_SCRIPT_LANGS:
        instruction += (
            " Keep technical acronyms and units (e.g. WBGT, ACGIH, OEL, "
            "PM2.5, kW, cal/cm2) in Latin script, as is standard practice "
            "in technical and engineering documentation in this language."
        )
    return instruction


