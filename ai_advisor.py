def get_configured_ai_api_key() -> str | None:
    """Returns the server-side Anthropic API key resolved from st.secrets/
    the environment at import time, or None if no server-side key is
    configured. app.py's sidebar calls this FIRST and only falls back to
    a per-operator manual text-input box when this returns None - see
    _render_ai_layer_sidebar() in app.py. Re-reads _AI_CONFIG rather than
    caching separately so a test that monkeypatches _AI_CONFIG directly
    is respected."""
    return _AI_CONFIG.get("api_key")

